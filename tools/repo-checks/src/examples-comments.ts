/**
 * Which comments under `examples/` cite something a reader cannot check in
 * the code.
 *
 * A comment states a reason that holds in the code next to it. It names no
 * spec or docs section, no G-number, no task number, no ruling and no
 * earlier version of the code. Those references go stale when the document
 * or the history moves, and the reader of the file has neither.
 *
 * The scanner reads comments only. It skips strings, template literals and
 * regular expression literals, so a version string or a CSS grid area in
 * code never matches. Markdown pages are docs; only the comments inside
 * their fenced code blocks are read.
 */

export interface CommentFile {
  /** The path relative to the workspace root. */
  readonly path: string;
  readonly text: string;
}

interface Comment {
  /** 1-based line of the first character of `text`. */
  readonly line: number;
  readonly text: string;
}

type Syntax = 'c' | 'css' | 'html' | 'hash';

const CODE_FENCE_LANGS = new Set([
  'ts',
  'tsx',
  'js',
  'jsx',
  'mjs',
  'cjs',
  'mts',
  'cts',
  'typescript',
  'javascript',
  'jsonc',
  'css',
  'html',
]);

/** The comment syntax of a file, or null when the file holds no comments to read. */
function syntaxOf(path: string): Syntax | null {
  const name = path.slice(path.lastIndexOf('/') + 1);
  if (name === 'worker-configuration.d.ts') return null; // generated by wrangler
  if (name === '.gitignore') return 'hash';
  if (name === '.swcrc') return 'c';
  const ext = name.slice(name.lastIndexOf('.') + 1);
  if (/^(?:[cm]?[jt]sx?|jsonc)$/.test(ext)) return 'c';
  if (ext === 'css') return 'css';
  if (ext === 'html') return 'html';
  if (/^(?:ya?ml|sh)$/.test(ext)) return 'hash';
  return null;
}

/** Whether a `/` after `previous` starts a regular expression literal. */
function startsRegex(previous: string): boolean {
  return previous === '' || /[(,=:[!&|?{};+\-*%<>~^]/.test(previous);
}

function scanC(text: string): Comment[] {
  const found: Comment[] = [];
  let line = 1;
  let previous = '';
  let i = 0;

  while (i < text.length) {
    const c = text[i];
    const next = text[i + 1];

    if (c === '\n') {
      line++;
      i++;
    } else if (c === '/' && next === '/') {
      const start = i + 2;
      let end = text.indexOf('\n', start);
      if (end === -1) end = text.length;
      found.push({ line, text: text.slice(start, end) });
      i = end;
    } else if (c === '/' && next === '*') {
      const start = i + 2;
      let end = text.indexOf('*/', start);
      if (end === -1) end = text.length;
      found.push({ line, text: text.slice(start, end) });
      line += text.slice(i, end).split('\n').length - 1;
      i = Math.min(end + 2, text.length);
    } else if (c === '"' || c === "'") {
      // A quote in JSX text has no partner, so a string ends at its line.
      i++;
      while (i < text.length && text[i] !== c && text[i] !== '\n') {
        i += text[i] === '\\' ? 2 : 1;
      }
      if (text[i] === c) i++;
      previous = c;
    } else if (c === '`') {
      i++;
      let depth = 0;
      while (i < text.length && (text[i] !== '`' || depth > 0)) {
        if (text[i] === '\\') i++;
        else if (text[i] === '$' && text[i + 1] === '{') {
          depth++;
          i++;
        } else if (text[i] === '}' && depth > 0) depth--;
        else if (text[i] === '\n') line++;
        i++;
      }
      i++;
      previous = '`';
    } else if (c === '/' && startsRegex(previous)) {
      i++;
      let inClass = false;
      while (i < text.length && text[i] !== '\n') {
        if (text[i] === '\\') i++;
        else if (text[i] === '[') inClass = true;
        else if (text[i] === ']') inClass = false;
        else if (text[i] === '/' && !inClass) break;
        i++;
      }
      i++;
      previous = '/';
    } else {
      if (c !== ' ' && c !== '\t' && c !== '\r') previous = c;
      i++;
    }
  }

  return found;
}

function scanCss(text: string): Comment[] {
  return [...text.matchAll(/\/\*([\s\S]*?)\*\//g)].map((match) => ({
    line: text.slice(0, match.index).split('\n').length,
    text: match[1] ?? '',
  }));
}

function scanHtml(text: string): Comment[] {
  return [...text.matchAll(/<!--([\s\S]*?)-->/g)].map((match) => ({
    line: text.slice(0, match.index).split('\n').length,
    text: match[1] ?? '',
  }));
}

function scanHash(text: string): Comment[] {
  return text.split('\n').flatMap((source, index) => {
    const at = source.indexOf('#');
    return at === -1 ? [] : [{ line: index + 1, text: source.slice(at + 1) }];
  });
}

function scan(text: string, syntax: Syntax): Comment[] {
  switch (syntax) {
    case 'c':
      return scanC(text);
    case 'css':
      return scanCss(text);
    case 'html':
      return scanHtml(text);
    case 'hash':
      return scanHash(text);
  }
}

/** The comments in the fenced code blocks of a Markdown page. */
function fencedComments(text: string): Comment[] {
  const found: Comment[] = [];
  const lines = text.split('\n');
  let fence: { lang: string; start: number; body: string[] } | null = null;

  lines.forEach((source, index) => {
    const open = /^\s*(?:```|~~~)\s*([\w-]*)/.exec(source);
    if (open === null) {
      fence?.body.push(source);
      return;
    }
    if (fence === null) {
      fence = {
        lang: (open[1] ?? '').toLowerCase(),
        start: index + 2,
        body: [],
      };
      return;
    }
    if (CODE_FENCE_LANGS.has(fence.lang)) {
      const syntax =
        fence.lang === 'css' ? 'css' : fence.lang === 'html' ? 'html' : 'c';
      const offset = fence.start - 1;
      for (const comment of scan(fence.body.join('\n'), syntax)) {
        found.push({ line: comment.line + offset, text: comment.text });
      }
    }
    fence = null;
  });

  return found;
}

interface Rule {
  readonly name: string;
  readonly pattern: RegExp;
}

/*
 * Each pattern reads one line of comment text. "used to" is history only after
 * a pronoun subject, so "a token used to resolve the sink" stays legal.
 */
const RULES: readonly Rule[] = [
  {
    name: 'a spec',
    pattern:
      /\bspec(?:\s*[(§]|\s+\d|'s\b)|\b(?:demo apps|ship systems|integrations|react|libraries)\s+specs?\b|^\W*specs?\b(?!\.)/i,
  },
  { name: 'a section number', pattern: /§|\bsections?\s+\d/i },
  { name: 'a docs section', pattern: /\b(?:docs|guide)\s+section\b/i },
  { name: 'a G-number', pattern: /\bG\d{1,2}b?\b/ },
  { name: 'a task number', pattern: /\bTasks?\s+\d+\b|\bT\d{1,2}\b/ },
  { name: 'a ruling', pattern: /\brul(?:ing|ed)s?\b/i },
  {
    name: 'an earlier version',
    pattern:
      /\bearlier versions?\b|\bpreviously\b|\bformerly\b|\brc\.\d+\b|\b(?:it|this|that|they|these|those|we|which|who|there)\s+used to\b/i,
  },
];

/** Whether a file under `examples/` is read at all. */
export function isRead(path: string): boolean {
  return (
    path.startsWith('examples/') &&
    !/(^|\/)(?:node_modules|dist|golden)\//.test(path) &&
    (path.endsWith('.md') || syntaxOf(path) !== null)
  );
}

/** One line per citing comment line, as `path:line [what] the comment text`. */
export function citations(files: readonly CommentFile[]): string[] {
  const hits: string[] = [];

  for (const { path, text } of files) {
    if (!isRead(path)) continue;
    const comments = path.endsWith('.md')
      ? fencedComments(text)
      : scan(text, syntaxOf(path) ?? 'c');

    for (const comment of comments) {
      comment.text.split('\n').forEach((source, offset) => {
        for (const rule of RULES) {
          if (rule.pattern.test(source)) {
            hits.push(
              `${path}:${comment.line + offset} cites ${rule.name}: ${source.trim()}`,
            );
            break;
          }
        }
      });
    }
  }

  return hits;
}
